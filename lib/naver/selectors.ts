// [추정] 글쓰기 진입 URL. 출처: 코디네이터가 공개 Selenium 자동화 글 4건 이상에서 교차
// 확인(브리프 <selector_hypotheses>). 두 가지 형태가 관찰됐다:
//   1. `https://blog.naver.com/{blogId}?Redirect=Write`
//   2. `https://blog.naver.com/PostWriteForm.naver?blogId={blogId}&Redirect=Write&categoryNo={n}`
// D14: 카테고리는 URL 파라미터가 아니라 에디터 진입 후 UI 에서 이름으로 고른다(별도
// selectCategory 단계) — 그래서 `categoryNo` 는 이 함수의 인자로 두지 않는다. 형태 1을
// 채택한다: 카테고리 없이도 항상 성립하는 형태이기 때문이다. 형태 2는 참고용으로만 남긴다.
export function writeUrl(blogId: string): string {
  return `https://blog.naver.com/${blogId}?Redirect=Write`;
}

